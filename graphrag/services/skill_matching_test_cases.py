from __future__ import annotations

import csv
import json
from pathlib import Path
from typing import Any

import psycopg
from psycopg.rows import dict_row
from psycopg.types.json import Jsonb

from models import SkillMatchingTestCaseInput


_SEED_CASES_PATH = (
    Path(__file__).resolve().parents[1]
    / "tests"
    / "fixtures"
    / "skill_matching_cases.csv"
)
_SEED_VERSION = 1
_EXPECTED_SEED_COLUMNS = [
    "Testid",
    "need-skills (Liste)",
    "has-skills (Liste)",
    "soll-Score",
]


class SkillMatchingTestCaseStore:
    def __init__(self, database_url: str) -> None:
        self.database_url = database_url

    @staticmethod
    def _read_seed_cases() -> list[SkillMatchingTestCaseInput]:
        with _SEED_CASES_PATH.open(encoding="utf-8", newline="") as source:
            reader = csv.DictReader(source)
            if reader.fieldnames != _EXPECTED_SEED_COLUMNS:
                raise ValueError(f"Unerwartete CSV-Spalten: {reader.fieldnames!r}")
            return [
                SkillMatchingTestCaseInput.model_validate(
                    {
                        "test_id": row["Testid"],
                        "need_skills": json.loads(row["need-skills (Liste)"]),
                        "has_skills": json.loads(row["has-skills (Liste)"]),
                        "expected_score": int(row["soll-Score"]),
                    }
                )
                for row in reader
            ]

    @staticmethod
    def _case_dict(row: dict[str, Any]) -> dict[str, Any]:
        return {
            "id": row["id"],
            "test_id": row["test_id"],
            "need_skills": row["need_skills"],
            "has_skills": row["has_skills"],
            "expected_score": row["expected_score"],
        }

    async def ensure_schema(self) -> None:
        async with await psycopg.AsyncConnection.connect(self.database_url) as connection:
            async with connection.cursor() as cursor:
                await cursor.execute(
                    """
                    CREATE TABLE IF NOT EXISTS skill_matching_test_cases (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        test_id TEXT NOT NULL UNIQUE,
                        need_skills JSONB NOT NULL CHECK (jsonb_typeof(need_skills) = 'array'),
                        has_skills JSONB NOT NULL CHECK (jsonb_typeof(has_skills) = 'array'),
                        expected_score INTEGER NOT NULL CHECK (expected_score BETWEEN 0 AND 100),
                        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                    )
                    """
                )
                await cursor.execute(
                    """
                    CREATE TABLE IF NOT EXISTS skill_matching_test_case_migrations (
                        version INTEGER PRIMARY KEY,
                        completed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                    )
                    """
                )
                await cursor.execute(
                    "SELECT 1 FROM skill_matching_test_case_migrations WHERE version = %s",
                    (_SEED_VERSION,),
                )
                if await cursor.fetchone():
                    return

                await cursor.execute("SELECT COUNT(*) FROM skill_matching_test_cases")
                count_row = await cursor.fetchone()
                if count_row and count_row[0] == 0:
                    for case in self._read_seed_cases():
                        await self._insert_case(cursor, case)

                await cursor.execute(
                    """
                    INSERT INTO skill_matching_test_case_migrations (version)
                    VALUES (%s)
                    ON CONFLICT (version) DO NOTHING
                    """,
                    (_SEED_VERSION,),
                )

    @staticmethod
    async def _insert_case(cursor: Any, case: SkillMatchingTestCaseInput) -> None:
        await cursor.execute(
            """
            INSERT INTO skill_matching_test_cases
                (test_id, need_skills, has_skills, expected_score)
            VALUES (%s, %s, %s, %s)
            """,
            (
                case.test_id,
                Jsonb([skill.model_dump() for skill in case.need_skills]),
                Jsonb(case.has_skills),
                case.expected_score,
            ),
        )

    async def list_cases(self) -> list[dict[str, Any]]:
        async with await psycopg.AsyncConnection.connect(self.database_url) as connection:
            async with connection.cursor(row_factory=dict_row) as cursor:
                await cursor.execute(
                    """
                    SELECT id, test_id, need_skills, has_skills, expected_score
                    FROM skill_matching_test_cases
                    ORDER BY id
                    """
                )
                rows = await cursor.fetchall()
        return [self._case_dict(row) for row in rows]

    async def create_case(self, case: SkillMatchingTestCaseInput) -> dict[str, Any]:
        async with await psycopg.AsyncConnection.connect(self.database_url) as connection:
            async with connection.cursor(row_factory=dict_row) as cursor:
                await self._insert_case(cursor, case)
                await cursor.execute(
                    """
                    SELECT id, test_id, need_skills, has_skills, expected_score
                    FROM skill_matching_test_cases
                    WHERE test_id = %s
                    """,
                    (case.test_id,),
                )
                row = await cursor.fetchone()
        if row is None:
            raise RuntimeError("Der gespeicherte Skill-Matching-Testfall konnte nicht gelesen werden.")
        return self._case_dict(row)

    async def update_case(self, case_id: int, case: SkillMatchingTestCaseInput) -> dict[str, Any] | None:
        async with await psycopg.AsyncConnection.connect(self.database_url) as connection:
            async with connection.cursor(row_factory=dict_row) as cursor:
                await cursor.execute(
                    """
                    UPDATE skill_matching_test_cases
                    SET test_id = %s,
                        need_skills = %s,
                        has_skills = %s,
                        expected_score = %s,
                        updated_at = CURRENT_TIMESTAMP
                    WHERE id = %s
                    RETURNING id, test_id, need_skills, has_skills, expected_score
                    """,
                    (
                        case.test_id,
                        Jsonb([skill.model_dump() for skill in case.need_skills]),
                        Jsonb(case.has_skills),
                        case.expected_score,
                        case_id,
                    ),
                )
                row = await cursor.fetchone()
        return self._case_dict(row) if row else None

    async def delete_case(self, case_id: int) -> bool:
        async with await psycopg.AsyncConnection.connect(self.database_url) as connection:
            result = await connection.execute(
                "DELETE FROM skill_matching_test_cases WHERE id = %s",
                (case_id,),
            )
        return result.rowcount > 0
